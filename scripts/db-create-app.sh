#!/usr/bin/env bash
# Provision one database + login role for a Sherpa app (idempotent).
#
#   ./scripts/db-create-app.sh des            # create (or confirm) database "des"
#   ./scripts/db-create-app.sh des --rotate   # also generate a new password
#
# Credentials go to ${DATA_ROOT}/_secrets/apps/<app>.db.env (mode 600), never to
# the terminal and never to git. The app's compose file reads that file.
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

app="${1:-}"
opt="${2:-}"

[[ "$app" =~ ^[a-z][a-z0-9_]{1,30}$ ]] \
  || die "Usage: $0 <app> [--rotate]   (app: lowercase letters, digits, underscore; starts with a letter)"
[[ -z "$opt" || "$opt" == "--rotate" ]] || die "Unknown option '$opt'"

require_mount
dk inspect -f '{{.State.Running}}' "$PG_CONTAINER" 2>/dev/null | grep -q true \
  || die "Container $PG_CONTAINER is not running. Run ./scripts/up.sh first."

psql_admin() { dk exec -i "$PG_CONTAINER" psql -U postgres -v ON_ERROR_STOP=1 -q "$@"; }

creds="${SECRETS_DIR}/apps/${app}.db.env"
mkdir -p "${SECRETS_DIR}/apps"

role_exists="$(psql_admin -tAc "SELECT 1 FROM pg_roles WHERE rolname = '${app}'")"

# Decide what to do with the role/password.
role_sql=""
password=""
if [[ "$role_exists" != "1" ]]; then
  password="$(openssl rand -hex 24)"
  role_sql="SELECT format('CREATE ROLE %I LOGIN PASSWORD %L', :'app', :'pw') \\gexec"
elif [[ "$opt" == "--rotate" ]]; then
  password="$(openssl rand -hex 24)"
  role_sql="SELECT format('ALTER ROLE %I PASSWORD %L', :'app', :'pw') \\gexec"
elif [[ ! -f "$creds" ]]; then
  die "Role '${app}' exists but ${creds} does not. Re-run with --rotate to set a new password."
else
  log "Role '${app}' already provisioned; making sure its database exists."
fi

# Stage the credentials file first so a password is never set without being recorded.
if [[ -n "$password" ]]; then
  (
    umask 077
    cat >"${creds}.tmp" <<EOF
# Generated by scripts/db-create-app.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit.
DB_HOST=${PG_CONTAINER}
DB_PORT=5432
DB_NAME=${app}
DB_USER=${app}
DB_PASSWORD=${password}
DATABASE_URL=postgresql://${app}:${password}@${PG_CONTAINER}:5432/${app}
EOF
  )
fi

# SQL goes over stdin so the password never appears in a process list.
psql_admin <<SQL
SET client_min_messages = warning;
\\set app '${app}'
\\set pw '${password}'
${role_sql}
SELECT format('CREATE DATABASE %I OWNER %I', :'app', :'app')
  WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = :'app') \\gexec
REVOKE ALL ON DATABASE :"app" FROM PUBLIC;
GRANT ALL ON DATABASE :"app" TO :"app";
\\connect :app
SET client_min_messages = warning;
CREATE EXTENSION IF NOT EXISTS vector;
SQL

[[ -n "$password" ]] && mv "${creds}.tmp" "$creds"

log "Database '${app}' ready (pgvector $(psql_admin -d "$app" -tAc "SELECT extversion FROM pg_extension WHERE extname='vector'"))."
log "Credentials: ${creds}"
log "Inside Docker networks the app connects to host '${PG_CONTAINER}' port 5432."
